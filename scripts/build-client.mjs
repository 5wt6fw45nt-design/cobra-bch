// Bundles the browser code into string modules the Worker serves:
//   client/bch-wallet.js → src/bchwallet.gen.js (/bch-wallet.js: WizardConnect + libauth, invoice payments)
//   client/bridge.js     → src/bridge.gen.js    (/bridge.js: + Cauldron, the PUSD ⇄ BCH bridge)
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
const LICENSES = '// Includes @wizardconnect/core and @wizardconnect/dapp (LGPL-3.0), @bitauth/libauth (MIT) and @cashlab (ISC).';
for (const [entry, out, name] of [['client/bch-wallet.js', 'src/bchwallet.gen.js', 'BCH_WALLET_JS'], ['client/bridge.js', 'src/bridge.gen.js', 'BRIDGE_JS']]) {
  const r = await build({ entryPoints: [entry], bundle: true, minify: true, format: 'esm', platform: 'browser', target: 'es2022', write: false, legalComments: 'eof' });
  const js = r.outputFiles[0].text;
  writeFileSync(out, `// Generated by scripts/build-client.mjs from ${entry}: do not edit.\n${LICENSES}\nexport const ${name} = ${JSON.stringify(js)};\n`);
  console.log(entry, (js.length / 1024).toFixed(0), 'KB');
}
