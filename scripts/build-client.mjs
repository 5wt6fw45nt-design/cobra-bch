// Bundles client/bch-wallet.js (WizardConnect + libauth) into src/bchwallet.gen.js, a string the Worker serves at /bch-wallet.js.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
const r = await build({ entryPoints: ['client/bch-wallet.js'], bundle: true, minify: true, format: 'esm', platform: 'browser', target: 'es2022', write: false, legalComments: 'eof' });
const js = r.outputFiles[0].text;
writeFileSync('src/bchwallet.gen.js', `// Generated by scripts/build-client.mjs from client/bch-wallet.js: do not edit.\n// Includes @wizardconnect/core and @wizardconnect/dapp (LGPL-3.0) and @bitauth/libauth (MIT).\nexport const BCH_WALLET_JS = ${JSON.stringify(js)};\n`);
console.log('bch-wallet.js', (js.length / 1024).toFixed(0), 'KB');
